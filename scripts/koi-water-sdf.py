# Coarse signed distance field of the visible water (water-mask-final.png), in pond px.
#   python3 scripts/koi-water-sdf.py  ->  src/pieces/koi-pond/water-sdf.ts
# > 0 inside open water (distance to nearest pad / lotus / paper edge), < 0 under them.
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt as edt
W, H, CELL = 800, 600, 10
m = np.array(Image.open("src/pieces/koi-pond/assets/water-mask-final.png").convert("L").resize((W, H), Image.BILINEAR)) > 128
sdf = edt(m) - edt(~m)
g = sdf[CELL // 2::CELL, CELL // 2::CELL]
gw, gh = g.shape[1], g.shape[0]
vals = np.clip(np.round(g / 2), -127, 127).astype(int).flatten()
with open("src/pieces/koi-pond/water-sdf.ts", "w") as f:
    f.write("// generated by scripts/koi-water-sdf.py — visible-water signed distance (units of 2px),\n")
    f.write(f"// {gw}x{gh} grid, {CELL}px cells, sampled at cell centres. >0 open water, <0 under pads/lotus/edge.\n")
    f.write(f"export const SDF_W = {gw};\nexport const SDF_H = {gh};\nexport const SDF_CELL = {CELL};\n")
    f.write("export const SDF = new Int8Array([" + ",".join(map(str, vals)) + "]);\n")
print(gw, gh, vals.max()*2, vals.min()*2)
